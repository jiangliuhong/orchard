import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { DatabaseSync, backup } from "node:sqlite";
import { test } from "node:test";
import { applyWorkspaceV11, inspectWorkspaceV11 } from "../src/migrations/workspace-v11.js";
import { captureRows } from "../src/migrations/mapping.js";
import { digest, FileStore } from "../src/persistence/files.js";
import { exampleFiles, temporary } from "./helpers.js";

test("Workspace v11 rehearsal preserves v10 business rows and rolls back an interrupted transform", async t => {
  const sourceRoot = temporary(t);
  const sourceDb = new DatabaseSync(join(sourceRoot, "workbench.db"));
  t.after(() => sourceDb.close());
  sourceDb.exec(readFileSync(new URL("./fixtures/migrations/database/v10.sql", import.meta.url), "utf8"));
  const files = exampleFiles("v11-rehearsal");
  const artifact = new FileStore(sourceRoot).saveTree(files);
  sourceDb.prepare(`INSERT INTO drafts(id,revision,artifact_path,validation_json,status,created_at,updated_at)
    VALUES('v10-draft',0,?,'{}','draft',1,1)`).run(artifact.path);
  const source = inspectWorkspaceV11(sourceRoot);
  assert.equal(source.from, 10);
  assert.equal(source.workflowBindings, 1);
  const copyRoot = temporary(t);
  const copyPath = join(copyRoot, "workbench.db");
  await backup(sourceDb, copyPath);
  const copy = new DatabaseSync(copyPath);
  t.after(() => copy.close());
  assert.equal(new FileStore(copyRoot).saveTree(files).path, artifact.path);
  const before = captureRows(copy);
  copy.exec("BEGIN IMMEDIATE");
  applyWorkspaceV11(copy, copyRoot);
  copy.exec("ROLLBACK");
  assert.equal(copy.prepare("PRAGMA user_version").get()!.user_version, 10);
  assert.deepEqual(captureRows(copy), before);
  copy.exec("BEGIN IMMEDIATE");
  applyWorkspaceV11(copy, copyRoot);
  copy.exec("COMMIT");
  assert.equal(copy.prepare("PRAGMA user_version").get()!.user_version, 11);
  assert.equal(copy.prepare("PRAGMA integrity_check").get()!.integrity_check, "ok");
  assert.deepEqual(copy.prepare("PRAGMA foreign_key_check").all(), []);
  const after = captureRows(copy);
  for (const [table, rows] of Object.entries(before)) assert.deepEqual(after[table], rows, table);
  const declaration = copy.prepare("SELECT config_json,content_hash FROM bridge_configuration").get()!;
  assert.equal(digest(String(declaration.config_json)), declaration.content_hash);
  assert.equal(copy.prepare("SELECT draft_id FROM agent_workspace_workflow_bindings").get()!.draft_id, "v10-draft");
  assert.equal(copy.prepare("SELECT state FROM agent_workspace_projection_state").get()!.state, "pending");
  assert.equal(inspectWorkspaceV11(sourceRoot).previewHash, source.previewHash);
  assert.ok(readFileSync(copyPath).length);
});
